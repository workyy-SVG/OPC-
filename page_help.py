def render_tutorial(page):
    title = {'策略回放':'历史模拟对比','公平实验室':'公平对比实验'}.get(page,page)
    tutorial = TUTORIALS[page]
    with st.expander('详细使用教程 · '+title):
        st.markdown('#### 这是什么')
        st.write(PAGE_HELP[page][0])
        st.markdown('#### 怎么做')
        st.markdown('\n\n'.join(f'{index}. {step}' for index,step in enumerate(tutorial['steps'],1)))
        st.markdown('#### 为什么这么做')
        st.write(tutorial['why'])
        st.markdown('#### 做了有什么用')
        st.write(tutorial['use'])


